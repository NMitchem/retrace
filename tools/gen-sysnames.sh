#!/bin/sh
# M50: generate crates/retrace-arch/src/sysnames.rs from the macOS SDK's sys/syscall.h, so a wall
# line names a syscall the way the SDK does. Run from the repository root after an SDK update;
# `the_generated_syscall_names_match_the_sdk_header` fails until it is re-run.
set -eu
H="$(xcrun --show-sdk-path)/usr/include/sys/syscall.h"
{
  echo "// Generated by tools/gen-sysnames.sh from the macOS SDK's sys/syscall.h. Do not edit; re-run the"
  echo "// script. The arch unit test the_generated_syscall_names_match_the_sdk_header re-reads the header."
  echo ""
  echo "/// The SDK's name for BSD syscall \`num\` (\`SYS_<name>\`), or None."
  echo "pub fn syscall_name(num: u64) -> Option<&'static str> {"
  echo "    Some(match num {"
  awk '$1 == "#define" && $2 ~ /^SYS_/ && $2 != "SYS_MAXSYSCALL" { printf "        %s => \"%s\",\n", $3, substr($2, 5) }' "$H"
  echo "        _ => return None,"
  echo "    })"
  echo "}"
} > crates/retrace-arch/src/sysnames.rs
